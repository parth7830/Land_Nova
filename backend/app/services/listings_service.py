class ListingsService:
    """
    Service interface for property listings.
    Currently backed by static demo data.
    Replace the data source methods to plug in a real listings provider.
    """

    def get_all(self) -> List[Dict[str, Any]]:
        return SAMPLE_LISTINGS

    def get_by_id(self, listing_id: str) -> Optional[Dict[str, Any]]:
        for prop in SAMPLE_LISTINGS:
            if prop["id"] == listing_id:
                return prop
        return None

    def search(
        self,
        query: Optional[str] = None,
        listing_type: Optional[str] = None,
        city: Optional[str] = None,
        min_price: Optional[int] = None,
        max_price: Optional[int] = None,
        bedrooms: Optional[int] = None,
        property_type: Optional[str] = None,
    ) -> List[Dict[str, Any]]:
        results = list(SAMPLE_LISTINGS)

        if query:
            q = query.lower()
            results = [
                p for p in results
                if q in p["title"].lower()
                or q in p["locality"].lower()
                or q in p["city"].lower()
                or q in p.get("description", "").lower()
            ]

        if listing_type:
            results = [p for p in results if p["listing_type"] == listing_type]

        if city:
            c = city.lower()
            results = [p for p in results if p["city"].lower() == c]

        if min_price is not None:
            results = [p for p in results if p["price"] >= min_price]

        if max_price is not None:
            results = [p for p in results if p["price"] <= max_price]

        if bedrooms is not None and bedrooms > 0:
            results = [p for p in results if p["bedrooms"] == bedrooms]

        if property_type:
            results = [p for p in results if p["type"] == property_type]

        return results

    def get_by_location(self, location_id: str) -> List[Dict[str, Any]]:
        return [p for p in SAMPLE_LISTINGS if p["location_id"] == location_id]

    def get_by_city(self, city: str) -> List[Dict[str, Any]]:
        c = city.lower()
        return [p for p in SAMPLE_LISTINGS if p["city"].lower() == c]


# Singleton instance
